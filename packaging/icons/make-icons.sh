#!/usr/bin/env bash
# make-icons.sh — draw Copper's Linux app icon from the macOS source.
#
#   packaging/icons/make-icons.sh /path/to/copper-ref/Icon/plate.jpg
#
# The macOS icon (copper-browser/Copper Icon/icon.swift) is plate.jpg — a
# macro of weathered copper — clipped to Apple's rounded square: the shape is
# 824 of 1024 units, corner radius 22.37 % of the side, with a soft shadow
# (18 % black, blur 24, 10 units down). This script draws the same thing as a
# scalable SVG (the photo embedded as a 1024 px JPEG, clipped to the same
# shape) and renders the hicolor PNGs from that SVG, so every size is the same
# drawing.
#
# Output (committed; rerun only when the Mac icon changes):
#   packaging/icons/com.copperbrowser.Copper.svg
#   packaging/icons/hicolor/<N>x<N>/apps/com.copperbrowser.Copper.png  N = 64 128 256 512
#
# Needs: ImageMagick (convert or magick), rsvg-convert (librsvg2-bin), base64.
# On Ubuntu: sudo apt install imagemagick librsvg2-bin
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
plate=${1:-}
if [[ -z $plate || ! -f $plate ]]; then
  echo "usage: $0 /path/to/Icon/plate.jpg" >&2
  exit 2
fi

im=convert
command -v magick >/dev/null 2>&1 && im=magick
command -v "$im" >/dev/null || { echo "make-icons: ImageMagick not found" >&2; exit 1; }
command -v rsvg-convert >/dev/null || { echo "make-icons: rsvg-convert not found (librsvg2-bin)" >&2; exit 1; }

id=com.copperbrowser.Copper
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# 1024 px is plenty for a 512 px raster (the plate is 824/1024 of the canvas)
# and keeps the SVG a reasonable size. Strip EXIF so the bytes are stable.
"$im" "$plate" -resize 1024x1024 -strip -sampling-factor 4:2:0 -quality 86 "$tmp/plate.jpg"
b64=$(base64 -w0 "$tmp/plate.jpg")

# Apple's grid, as in icon.swift: plate at (100,100) 824x824, radius 824*0.2237.
cat >"$here/$id.svg" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Copper app icon. Generated by packaging/icons/make-icons.sh from the macOS
     icon (Icon/plate.jpg + Icon/icon.swift); do not edit by hand. -->
<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink"
     width="1024" height="1024" viewBox="0 0 1024 1024">
  <defs>
    <clipPath id="plate">
      <rect x="100" y="100" width="824" height="824" rx="184.33" ry="184.33"/>
    </clipPath>
    <filter id="soft" x="-20%" y="-20%" width="140%" height="140%">
      <feGaussianBlur stdDeviation="12"/>
    </filter>
  </defs>
  <rect x="100" y="110" width="824" height="824" rx="184.33" ry="184.33"
        fill="#000000" fill-opacity="0.18" filter="url(#soft)"/>
  <image x="100" y="100" width="824" height="824" preserveAspectRatio="xMidYMid slice"
         clip-path="url(#plate)" xlink:href="data:image/jpeg;base64,$b64"/>
</svg>
EOF

for n in 64 128 256 512; do
  mkdir -p "$here/hicolor/${n}x${n}/apps"
  rsvg-convert -w "$n" -h "$n" -f png -o "$tmp/$n.png" "$here/$id.svg"
  # Drop timestamps/text chunks so a rerun produces identical bytes.
  "$im" "$tmp/$n.png" -strip -define png:exclude-chunks=date,time "$here/hicolor/${n}x${n}/apps/$id.png"
done

echo "make-icons: wrote $here/$id.svg and hicolor 64/128/256/512"
